#!/usr/bin/env python3
"""KWCOV: render docs/hf/KEYWORD_COVERAGE.md and docs/hf/OBSERVABLE_COVERAGE.md from the two CSVs.

    python scripts/kwcov/render.py        (after inventory.py and observables.py)
"""
from __future__ import annotations

import csv
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
D = ROOT / "docs/hf"

KW_HEAD = """# TALYS-2.25 keyword coverage of the `physics/hf` engine

Generated by `scripts/kwcov/inventory.py` + `scripts/kwcov/render.py` from the stock TALYS-2.25 source
(`source/checkkeyword.f90` master list, the keyword loops of `source/input_*.f90`, `getvalues.f90` classes) and a
`USER INPUT FILE + DEFAULTS` echo (n + Fe-56, `reaction n`). Machine-readable copy: `keyword_coverage.csv`.
Plan for the gaps: `COVERAGE_PLAN.md`. Observables: `OBSERVABLE_COVERAGE.md`.

**Count check.** `checkkeyword.f90` declares `numkey=447`, one of which is the blank entry: **446 keywords**. The
manual (`doc/talys.pdf`, keyword chapter) documents the same list; every keyword is parsed in one `input_*.f90`
except the four main keywords and a handful read in `readinput.f90`/`getvalues.f90`.

## Status values

| status | meaning |
|---|---|
| SUPPORTED | read by the engine (deck line via `INCOGNITA_TALYS_FIT_LINES`, or `default_options`/`default_params` overrides) and the variable it sets reaches engine physics code. `evidence` says how we know: `test:<file>` = a test names the keyword; `grep` = only the code path was found (not yet compared with stock TALYS); `manual` = read by hand |
| READ_ONLY_DEFAULT | only the default works; any other value is refused at run time (`defaults.UNPORTED`, `structure/levels.py`) |
| IGNORED | parsed (into `Options`/`Params`, or dropped by `fitlib._SKIP`) but nothing in the engine reads it: a deck using it runs silently on the default. Several of these set other defaults through TALYS's cascade, which IS honoured (notes say so) |
| MISSING | not parsed: a deck line with it is rejected (`default_options` raises `KeyError`; `fitlib` reports it skipped) |
| NA | output files, paths, ECIS plumbing, labels: no meaning for an engine that returns arrays. The observables those switches gate are tracked in `OBSERVABLE_COVERAGE.md` |

**Caveat on SUPPORTED.** The automatic class is "read and reaches physics code". Only rows with `evidence` other than
`grep` have a test; the batches in `COVERAGE_PLAN.md` upgrade `grep` rows as they compare with stock TALYS. Options
keywords take their global form; the per-nucleus / per-particle forms TALYS has for them (`ldmodel 2 26 57`,
`colenhance y 26 57`, `nlevels 25 56 5`, `maxlevelsbin p 5`, `branch Z A ilev0 ...`) are read since KWCOV B2 (and
`nlow`/`ntop Z A n [ibar]`, `skipcn Z A`, `levelfile`/`deformfile Z <file>` since B5), and any other multi-word form
of an Options keyword is refused (`Params` keywords take per-nucleus forms through `fitlib`). Since B5 a deck line
with a keyword the port does not know is refused too (it was skipped without a word); NA keywords stay accepted.
A deck is a talys.inp (`physics/hf/input/deck.py`) or deck lines in `INCOGNITA_TALYS_FIT_LINES`; the lines act with
or without an `INCOGNITA_TALYS_FIT` arm (before B2 they were dropped without one). Energy-dependent adjustment forms
(`v1adjust n 1. Ea Eb Em D`, `awdadjust n 1. file.table`, adjust.f90) are not read: as a deck line they are refused
(B2), from a best file or fitted library they are left out with a warning; `physics/hf/eadj.py` (ENGADJ) is our own
equivalent keyword.
"""

OBS_HEAD = """# TALYS-2.25 observable coverage of the `physics/hf` engine

Hand-curated in `scripts/kwcov/observables.py` (machine-readable copy: `observable_coverage.csv`), one row per TALYS
output family. `talys_writer` is the output routine (`file:line`) in `~/opt/talys-src/source`. `batch` points to
`COVERAGE_PLAN.md`.

| status | meaning |
|---|---|
| SUPPORTED | in `Results` (`physics/hf/results.py`) on the production C path with default inputs; covered by the E2E/A-mult gates |
| PARTIAL | produced, but only behind an `INCOGNITA_*` switch, on one driver, or for a subset (notes say which) |
| INTERNAL | computed by the engine, not carried out in `Results` |
| MISSING | not computed |
| NA | TALYS diagnostics or plumbing with no meaning for us |

TALYSworld (the IAEA web calculator, and our `scripts/talysworld/engine_job.py`) shows total, elastic, nonelastic,
capture, (n,p), (n,a), (n,2n), inelastic and fission: all SUPPORTED.
"""


def table(rows, cols):
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        out.append("| " + " | ".join(str(r[c]).replace("|", "/") for c in cols) + " |")
    return "\n".join(out)


def main() -> None:
    kw = list(csv.DictReader(open(D / "keyword_coverage.csv", encoding="utf-8")))
    c = Counter(r["status"] for r in kw)
    by_group = defaultdict(Counter)
    for r in kw:
        by_group[r["group"] or "(main/readinput)"][r["status"]] += 1
    sts = ["SUPPORTED", "READ_ONLY_DEFAULT", "IGNORED", "MISSING", "NA"]
    parts = [KW_HEAD, "## Totals\n", table([{"status": s, "keywords": c.get(s, 0)} for s in sts]
                                          + [{"status": "**total**", "keywords": len(kw)}], ["status", "keywords"]),
             "\nOf the SUPPORTED rows, %d have a test naming the keyword, %d are code-path only (`grep`).\n" % (
                 sum(1 for r in kw if r["status"] == "SUPPORTED" and r["evidence"].startswith("test")),
                 sum(1 for r in kw if r["status"] == "SUPPORTED" and r["evidence"] == "grep")),
             "## By TALYS input group\n",
             table([{"group": g, **{s: by_group[g].get(s, 0) for s in sts}} for g in sorted(by_group)], ["group"] + sts),
             "\n## Every keyword\n",
             table(kw, ["keyword", "group", "type", "default", "status", "evidence", "where", "notes"]), ""]
    (D / "KEYWORD_COVERAGE.md").write_text("\n".join(parts), encoding="utf-8")

    ob = list(csv.DictReader(open(D / "observable_coverage.csv", encoding="utf-8")))
    oc = Counter(r["status"] for r in ob)
    osts = ["SUPPORTED", "PARTIAL", "INTERNAL", "MISSING", "NA"]
    parts = [OBS_HEAD, "## Totals\n", table([{"status": s, "observables": oc.get(s, 0)} for s in osts]
                                            + [{"status": "**total**", "observables": len(ob)}], ["status", "observables"]),
             "\n## Every observable family\n",
             table(ob, ["observable", "talys_files", "talys_writer", "gating_keywords", "status", "where", "batch", "notes"]), ""]
    (D / "OBSERVABLE_COVERAGE.md").write_text("\n".join(parts), encoding="utf-8")
    print(dict(c), dict(oc))


if __name__ == "__main__":
    main()
