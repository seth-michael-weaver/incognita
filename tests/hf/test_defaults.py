"""T3: TALYS defaults (physics/hf/input/defaults.py) against TALYS's own echo of what it resolved.

Reference. TALYS prints every resolved global switch in talys.out ("USER INPUT FILE + DEFAULTS",
inputout.f90) and, with `partable y`, every adjustable parameter per nucleus (partable.f90) plus
the general ones at the end of a run (finalout.f90). The cases are a 1 MeV run of each of the 24
reference targets, the same targets on a two-energy grid (so the structure-dependent onsets
print as numbers), and explicit-keyword cases chosen to exercise each dependent default: the
`ldmodel 1` actinide trap, `strength 8`, `ldmodel 2/5`, `micro y`, `endf y`, `astro y`,
`massdis y`, `soukho y`, `colenhance y`, `widthmode 0`, `widthfluc y`, `preequilibrium n`, OMP
geometry links and global level-density keywords, and proton and alpha projectiles.

Data. The raw runs live in features/hf_reference/t3_echo/<case>/ (talys.inp, talys_head.out,
parameters.dat), produced on a second machine with TALYS built from the same source as the first
(input_*.f90 md5-identical). Every case's input is recorded in the fixture, so the runs can be
regenerated by feeding `inp` (plus `energies` when present) to any TALYS 2.x binary with
`partable y`. The committed fixture tests/hf/fixtures/t3_defaults_echo.json.gz holds the parsed
echoes, the general parameters and the per-nucleus parameters of a subset, so these tests run
without the raw directory; rebuild it with

    uv run python -m tests.hf.test_defaults build-fixture
"""

from __future__ import annotations

