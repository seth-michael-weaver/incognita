@needs_reference
def test_reference_covers_every_target_and_the_cascades():
    names = set(CASES)
    assert sum(n.startswith("default__") for n in names) == 24
    assert sum(n.startswith("grid__") for n in names) == 24
    for n in ("ldmodel1__U238", "strength8__Au197", "micro__Co059", "endf__Fe056", "astro__Fe056",
              "massdis__U235", "soukho__Pu239", "proton__Ni058", "alpha__Bi209"):  # fmt: skip
        assert n in names, n


@needs_reference
@pytest.mark.parametrize("name", sorted(CASES))
def test_options_reproduce_the_talys_echo(name):
    c = CASES[name]
    structure = _structure_from_grid(CASES)
    o, exp, _ = _expected_for_case(name, c, structure)
    bad = D.compare_echo(exp, c["echo"])
    assert not bad, f"{name}: (expected, TALYS printed) {bad}"
    unmodelled = set(c["echo"]) - set(exp) - D.ECHO_NOT_MODELLED
    energy_keys = {"widthfluc", "urr", "preequilibrium", "multipreeq", "elow"}
    assert unmodelled <= energy_keys, (
        f"{name}: echo keys neither modelled nor excluded: {unmodelled}"
    )


@needs_reference
@pytest.mark.parametrize("name", sorted(n for n in CASES if CASES[n].get("general")))
def test_general_parameters(name):
    c = CASES[name]
    Z, A, proj, _, opt, par = _split_inp(c["inp"])
    o = D.default_options(Z, A, proj, opt)
    p = D.default_params(Z, A, o, _params_overrides(par))
    checked, bad = 0, []
    for key, particle, printed in c["general"]:
        k = key.lower()
        if key in GENERAL_OPTIONS:
            got = getattr(o, GENERAL_OPTIONS[key])
            want = ("y" if got else "n") if isinstance(got, bool) else str(got)
            ok = want == printed
        else:
            spec = D.PARAM_SPECS.get(k)
            if spec is None or spec.resolved_by:
                continue
            if particle is not None:
                val = p.at(k, D.PARSYM.index(particle))
            elif k in GENERAL_CN_ENTRY:
                val = p.at(k, 0, 0)
            else:
                val = p[k]
            want = float(val)
            ok = abs(want - float(printed)) <= 1e-5 + 1e-5 * abs(float(printed))
        checked += 1
        if not ok:
            bad.append((key, particle, want, printed))
    assert checked > 40
    assert not bad, f"{name}: (keyword, particle, ours, TALYS) {bad}"


@needs_reference
@pytest.mark.parametrize("name", sorted(n for n in CASES if CASES[n].get("partable")))
def test_per_nucleus_parameters(name):
    c = CASES[name]
    Z, A, proj, _, opt, par = _split_inp(c["inp"])
    o = D.default_options(Z, A, proj, opt)
    p = D.default_params(Z, A, o, _params_overrides(par))
    checked, bad = 0, []
    for key, z, a, printed, qual in c["partable"]:
        k, comp = UPBEND.get(key.lower(), (key.lower(), None))
        spec = D.PARAM_SPECS.get(k)
        if spec is None:
            continue
        zix, nix = o.Zinit - z, o.Ninit - (a - z)
        if spec.resolved_by and not (k in ("ctable", "ptable") and o.ldmodel_of(zix, nix) <= 3):
            continue
        q = qual.split()
        idx = [zix, nix]
        if len(spec.dims) == 3:
            idx.append(int(q[0]))
        elif len(spec.dims) >= 4:
            idx += [1 if q[0][0] == "E" else 0, int(q[0][1:])]
            if len(spec.dims) == 5:
                idx.append(comp if comp else (int(q[1]) if len(q) > 1 else 1))
        want = float(p.at(k, *idx))
        # f10.5 prints five decimals; es12.5 (upbend) six significant digits
        tol = 1e-5 * abs(printed) + (1e-15 if "upbend" in k else 6e-6)
        checked += 1
        if abs(want - printed) > tol:
            bad.append((key, z, a, qual, want, printed))
    assert checked > 100
    assert not bad, f"{name}: {len(bad)} mismatches, first {bad[:5]}"


