import json
import os
import sys
from pathlib import Path

import pytest
import torch

from physics.hf.input import defaults as D

ROOT = Path(__file__).resolve().parents[2]
RAW = Path(os.environ.get("INCOGNITA_T3_ECHO_RAW", ROOT / "features" / "hf_reference" / "t3_echo"))
FIXTURE = Path(__file__).parent / "fixtures" / "t3_defaults_echo.json.gz"

SYMBOL_Z = {
    "Ca": 20, "Fe": 26, "Co": 27, "Ni": 28, "Zr": 40, "Nb": 41, "Mo": 42, "Sn": 50, "I": 53,
    "Ba": 56, "Ce": 58, "Au": 79, "Pb": 82, "Bi": 83, "Nd": 60, "Sm": 62, "Gd": 64, "Er": 68,
    "W": 74, "Th": 90, "U": 92, "Pu": 94, "Am": 95,
}  # fmt: skip
# per-nucleus parameters.dat rows are kept in the fixture only for these cases (size)
PARTABLE_CASES = (
    "default__Fe056", "default__Sm152", "default__U238", "default__Am241", "ldmodel1__U238",
    "ldmodel1__Th232", "strength8__Au197", "ldmodel2__Zr090", "ldmodel5__Sm152", "alpha__Bi209",
    "proton__Ni058", "alphald__Fe056", "rvadjust__Fe056",
)  # fmt: skip
UPBEND = {
    "upbendc": ("upbend", 1), "upbende": ("upbend", 2), "upbendf": ("upbend", 3),
    "upbendcadjust": ("upbendadjust", 1), "upbendeadjust": ("upbendadjust", 2),
    "upbendfadjust": ("upbendadjust", 3),
}  # fmt: skip
# general-block keywords that are Options, not Params
GENERAL_OPTIONS = {
    "ldmodel": "ldmodelCN", "colenhance": "flagcolall", "strength": "strength",
    "strengthM1": "strengthM1", "fismodel": "fismodel", "deuteronomp": "deuteronomp",
    "alphaomp": "alphaomp",
}  # fmt: skip
# general-block keywords that hold the (0,0) entry of a per-nucleus parameter
GENERAL_CN_ENTRY = {"alphald", "betald", "gammashell1", "pshiftconstant"}


