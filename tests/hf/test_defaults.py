def _read_inp(text: str) -> dict[str, str]:
    return dict(line.split(None, 1) for line in text.splitlines() if line.strip())


def build_fixture(raw: Path = RAW, out: Path = FIXTURE) -> dict:
    cases = {}
    for d in sorted(p for p in raw.iterdir() if (p / "talys_head.out").exists()):
        echo = D.parse_talys_echo((d / "talys_head.out").read_text())
        pdat = (d / "parameters.dat").read_text() if (d / "parameters.dat").exists() else ""
        c = {
            "inp": _read_inp((d / "talys.inp").read_text()),
            "done": json.loads((d / "done.json").read_text()),
            "echo": {k: v for k, v in echo.items() if k not in D.ECHO_NOT_MODELLED},
            "general": D.parse_partable_general(pdat),
        }
        if d.name in PARTABLE_CASES:
            c["partable"] = D.parse_partable(pdat)
        cases[d.name] = c
    out.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(out, "wt") as f:
        json.dump(
            {"source": "features/hf_reference/t3_echo", "cases": cases}, f, separators=(",", ":")
        )
    return cases


def _cases() -> dict:
    if RAW.is_dir() and any(RAW.glob("*/talys_head.out")):
        cases = {}
        for d in sorted(p for p in RAW.iterdir() if (p / "talys_head.out").exists()):
            pdat = (d / "parameters.dat").read_text() if (d / "parameters.dat").exists() else ""
            cases[d.name] = {
                "inp": _read_inp((d / "talys.inp").read_text()),
                "echo": D.parse_talys_echo((d / "talys_head.out").read_text()),
                "general": D.parse_partable_general(pdat),
                "partable": D.parse_partable(pdat),
            }
        return cases
    if FIXTURE.exists():
        with gzip.open(FIXTURE, "rt") as f:
            return json.load(f)["cases"]
    return {}


CASES = _cases()
needs_reference = pytest.mark.skipif(
    not CASES, reason="no TALYS defaults echo (raw dir or fixture)"
)


def _split_inp(inp: dict[str, str]):
    """(Z, A, projectile, energy, Options keywords, Params keyword forms) from a case input."""
    kv = dict(inp)
    proj, sym, A = kv.pop("projectile"), kv.pop("element").capitalize(), int(kv.pop("mass"))
    energy = kv.pop("energy")
    kv.pop("partable", None)
    opt = {k: v for k, v in kv.items() if k in D.OPTION_KEYWORDS}
    par = {k: v for k, v in kv.items() if k not in D.OPTION_KEYWORDS}
    return SYMBOL_Z[sym], A, proj, energy, opt, par


def _params_overrides(par: dict[str, str]) -> dict[str, object]:
    """Keyword forms from a case input -> default_params overrides (scalar or full tensor)."""
    ov: dict[str, object] = {}
    for k, v in par.items():
        spec = D.PARAM_SPECS[k.lower()]
        words = v.split()
        if len(words) == 1:
            ov[spec.keyword] = float(words[0])
        elif len(words) == 2 and words[0] in D.PARSYM and len(spec.dims) == 1:
            ov.setdefault(spec.keyword, {})[words[0]] = float(words[1])
        else:
            raise NotImplementedError(f"keyword form {k} {v}")
    return ov


def _structure_from_grid(cases: dict) -> dict[tuple[str, str], tuple[float, float]]:
    """(projectile, target tag) -> (S_projectile, epreeq) as TALYS printed them on the two-energy
    grid. Used to resolve the sentinels in the *other* runs of the same target."""
    out = {}
    for name, c in cases.items():
        if not name.startswith("grid") or c["inp"].get("endf") == "y":
            continue
        e = c["echo"]
        try:
            out[(c["inp"]["projectile"], name.split("__")[1])] = (
                float(e["widthfluc"]), float(e["preequilibrium"]),
            )  # fmt: skip
        except (KeyError, ValueError):
            continue
    return out


def _expected_for_case(name: str, c: dict, structure: dict):
    Z, A, proj, energy, opt, par = _split_inp(c["inp"])
    o = D.default_options(Z, A, proj, opt)
    st = structure.get((proj, name.split("__")[1]))
    e_inc = None
    if st is not None:
        o = D.resolve_structure_defaults(o, s_projectile_mev=st[0], e_last_level_mev=st[1])
    numeric_onsets = energy == "energies" or o.flagastro  # Ninc > 1 prints the onset energies
    if st is not None and not numeric_onsets:
        e_inc = float(energy)
    exp = D.echo_expected(o, e_inc)
    if st is not None and numeric_onsets:
        for key, f in (("widthfluc", "ewfc_mev"), ("preequilibrium", "epreeq_mev"),
                       ("multipreeq", "emulpre_mev")):  # fmt: skip
            exp[key] = getattr(o, f)
        exp["urr"] = o.eurr_mev if o.flagurr else "n"
    return o, exp, par


