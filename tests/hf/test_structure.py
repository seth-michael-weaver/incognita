"""T2 structure: fixed-format readers, masses and separation energies, discrete levels and gamma
cascades, deformation, resonance data and nuclide bookkeeping, against TALYS (gate A-struct).

Two kinds of test:

* unit tests that need only TALYS's structure database (skipped without it), including a
  bit-exact check of the Duflo-Zuker port against the Fortran compiled from TALYS's own
  duflo.f90 with the TALYS build flags (the table below), and physical-value unit checks;
* acceptance tests against the reference dumps (skipped when absent): every number TALYS printed
  for structure is regenerated by the port and compared as TALYS formatted it -- discrete data
  must match character for character, numbers to the printed precision (A-struct: 1e-5).

Reference sources, in order: the extracted-directory tree named by $INCOGNITA_HF_STRUCT_EXTRACT
(``<variant>__<target>/levels*.out`` ...), then the tarballs in
``physics.hf.reference.reference_dir() / "raw"``. One variant per target (structure does not
depend on the variant). Run ``python tests/hf/test_structure.py`` for the gate report.
"""

