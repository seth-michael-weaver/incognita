def _extract_roots() -> list[Path]:
    env = os.environ.get("INCOGNITA_HF_STRUCT_EXTRACT")
    return [Path(p) for p in env.split(os.pathsep)] if env else []


@cache
def _sources() -> dict[str, tuple[str, object]]:
    """target tag -> (variant, loader(name_regex) -> {filename: text})"""
    out: dict[str, tuple[str, object]] = {}
    pref = {"default": 0, "wfc_off": 1}
    for root in _extract_roots():
        for d in sorted(root.glob("*__*")):
            if not d.is_dir():
                continue
            variant, tag = d.name.split("__", 1)
            if variant not in pref:
                continue
            if tag in out and pref[out[tag][0]] <= pref[variant]:
                continue

            def load(rx, d=d):
                r = re.compile(rx)
                return {p.name: p.read_text() for p in d.iterdir() if r.fullmatch(p.name)}

            out[tag] = (variant, load)
    try:
        from physics.hf import reference as ref

        raw = ref.reference_dir() / "raw"
    except Exception:  # pragma: no cover
        raw = None
    if raw is not None and raw.is_dir():
        for tgz in sorted(raw.glob("*__*.tar.gz")):
            if tgz.stat().st_size == 0 or tgz.name.startswith("FAILED"):
                continue
            variant, tag = tgz.name[: -len(".tar.gz")].split("__", 1)
            if variant not in pref or (tag in out and pref[out[tag][0]] <= pref[variant]):
                continue

            def load(rx, tgz=tgz):
                r = re.compile(rx)
                got = {}
                with tarfile.open(tgz) as tf:
                    for mem in tf:
                        name = mem.name.rsplit("/", 1)[-1]
                        if mem.isfile() and r.fullmatch(name):
                            got[name] = tf.extractfile(mem).read().decode("latin-1")
                return got

            out[tag] = (variant, load)
    return out


def _targets() -> list[str]:
    return sorted(_sources()) if STRUCTURE.is_dir() else []


needs_dumps = pytest.mark.skipif(not _targets(), reason="reference dumps not available")


def _target_za(tag: str) -> tuple[int, int]:
    from physics.hf.core.constants import NUC

    sym = re.match(r"[A-Za-z]+", tag).group(0)
    Z = [s.strip().lower() for s in NUC].index(sym.lower()) + 1
    return Z, int(tag[len(sym) :])


def _meta(text: str) -> dict[str, str]:
    out = {}
    for line in text.splitlines():
        if line.startswith("#") and not line.startswith("##") and ":" in line:
            k, _, v = line[1:].partition(":")
            if v.strip():
                out.setdefault(k.strip(), v.strip())
    return out


def _rows(text: str) -> list[str]:
    return [ln for ln in text.splitlines() if ln and not ln.startswith("#")]


def _es(x: float, w: int = 15) -> str:
    return f"{float(np.float32(x)):{w}.6E}"


@cache
def _setup(tag: str):
    from physics.hf.input.defaults import default_options
    from physics.hf.structure.masses import masses

    Z, A = _target_za(tag)
    o = default_options(Z, A)
    return o, masses(o)


def _render_levels(lv) -> list[str]:
    """levelsout.f90 write statements."""
    f = np.float32
    lines = []
    cpar = {-1: "-", 0: " ", 1: "+"}
    for i in range(lv.nlev + 1):
        tr = float(lv.half_life_ripl_s[i])
        taus = f"{float(f(tr)):15.6E}" if tr != 0.0 else " " * 15
        lines.append(
            f"{int(lv.levnum[i]):6d}{'':9}{float(f(lv.e_mev[i])):15.6E}{'':7}"
            f"{float(lv.spin[i]):4.1f}{'':13}{cpar[int(lv.parity[i])]}{'':9}"
            f"{int(lv.nbranch[i]):6d}{'':51}{taus}{'':6}{lv.assign[i]} {lv.ensdf[i]}"
        )
        for k in range(int(lv.nbranch[i])):
            pct = float(f(lv.branch_ratio[i, k]) * f(100.0))
            lines.append(
                f"{'':75}--->{int(lv.branch_to[i, k]):6d}{'':9}{pct:8.4f}{'':4}"
                f"{float(f(lv.conversion[i, k])):15.6E}{'':26}{lv.branch_assign[i][k]}"
            )
    return [ln.rstrip() for ln in lines]


@cache
def _populations(tag: str):
    """(energies, populated(Zcomp, Ncomp, E), flagpop) from TALYS's own talys.out record of
    which compound nuclei multiple emission processed at each incident energy."""
    o, _ = _setup(tag)
    _, load = _sources()[tag]
    texts = load(r"populations\.txt|talys_head\.out|talys\.out")
    if "talys.out" in texts:
        body = head = texts["talys.out"]
    elif "populations.txt" in texts:
        body, head = texts["populations.txt"], texts.get("talys_head.out", "")
    else:
        return None
    mm = re.search(r"^\s*outpopulation\s+([yn])\s+flagpop", head, re.M)
    if mm is None:
        return None
    flagpop = mm.group(1) == "y"
    energies, pop, cur = [], {}, None
    for line in body.splitlines():
        e = re.search(r"RESULTS FOR E=\s*([\d.Ee+-]+)", line)
        if e:
            cur = float(e.group(1))
            energies.append(cur)
            pop.setdefault(cur, set())
            continue
        p = re.search(r"Population of Z=\s*(\d+) N=\s*(\d+)", line)
        if p and cur is not None:
            Z, N = int(p.group(1)), int(p.group(2))
            pop[cur].add((o.Zinit - Z, o.Ninit - N))
    if not energies:
        return None

    def populated(zc: int, nc: int, e: float) -> bool:
        return (zc, nc) in pop.get(e, ())

    return tuple(energies), populated, flagpop


def gate_levels_and_masses(tag: str) -> dict:
    """Compare every levels*.out and gamma*.tot of one target: counts and relative errors."""
    from physics.hf.input.nuclides import structure_history
    from physics.hf.structure.levels import discrete_levels, gamma_cascade

    o, m = _setup(tag)
    variant, load = _sources()[tag]
    lev_files = load(r"levels\d{6}\.out")
    gam_files = load(r"gamma\d{6}\.tot")
    pops = _populations(tag)
    if pops is None:
        pytest.skip(f"{tag}: no talys.out population record to replay the call sequence")
    energies, populated, flagpop = pops
    hist = structure_history(o, energies, populated, m, flagpop)
    prior, prior_s = hist.prior_call, hist.prior_call_at_structure
    res = {
        "files": 0,
        "lines": 0,
        "line_mismatch": [],
        "num_rel": [],
        "num_mismatch": [],
        "gamma_lines": 0,
        "gamma_mismatch": [],
    }
    for name, text in sorted(lev_files.items()):
        Z, A = int(name[6:9]), int(name[9:12])
        lv = discrete_levels(Z, A, o, m, prior_call=(o.Zinit - Z, o.Ninit - (A - Z)) in prior)
        want = [ln.rstrip() for ln in _rows(text)]
        got = _render_levels(lv)
        res["files"] += 1
        res["lines"] += len(want)
        if len(want) != len(got):
            res["line_mismatch"].append((name, "count", len(want), len(got)))
        for a, b in zip(want, got, strict=False):
            if a != b:
                res["line_mismatch"].append((name, a, b))
        meta = _meta(text)
        Zix, Nix = o.Zinit - Z, o.Ninit - (A - Z)
        port = {
            "nuclear mass [amu]": float(m.mass_amu[Zix, Nix]),
            "neutron separation energy [MeV]": float(m.s_mev[Zix, Nix, 1]),
            "proton separation energy [MeV]": float(m.s_mev[Zix, Nix, 2]),
            "alpha separation energy [MeV]": float(m.s_mev[Zix, Nix, 6]),
        }
        for k, v in port.items():
            t = float(meta[k])
            if f"{v:13.6E}".strip() != meta[k]:
                res["num_mismatch"].append((name, k, meta[k], f"{v:13.6E}"))
            if t != 0.0:
                res["num_rel"].append(abs(v / t - 1.0))
        if int(meta["number of excited levels"]) != lv.nlev:
            res["num_mismatch"].append((name, "nlev", meta["number of excited levels"], lv.nlev))
        gname = f"gamma{name[6:12]}.tot"
        if gname in gam_files:
            zn = (o.Zinit - Z, o.Ninit - (A - Z))
            if (zn in prior) != (zn in prior_s):  # gamma*.tot was written at structure time
                lv = discrete_levels(Z, A, o, m, prior_call=zn in prior_s)
            gwant = [ln.rstrip() for ln in _rows(gam_files[gname])]
            ggot = []
            for g in gamma_cascade(lv, o.flagelectron):
                ggot.append(
                    f"{g['level']:6d}{'':9}{_es(g['e_mev'])}{len(g['lines']):6d}{'':9}"
                    f"{_es(g['yield'])}".rstrip()
                )
                for p, d, eg, br, pe, de in g["lines"]:
                    ggot.append(
                        f"{'':60}{p:6d}{'':9}{d:6d}{'':9}{_es(eg)}{_es(br)}{_es(pe)}"
                        f"{_es(de)}".rstrip()
                    )
            res["gamma_lines"] += len(gwant)
            for a, b in zip(gwant, ggot, strict=False):
                if a != b:
                    res["gamma_mismatch"].append((gname, a, b))
            if len(gwant) != len(ggot):
                res["gamma_mismatch"].append((gname, "count", len(gwant), len(ggot)))
    return res


def gate_deformation(tag: str) -> dict:
    from physics.hf.input.nuclides import weak_coupling_core
    from physics.hf.structure.deformation import deformation, weak_coupling
    from physics.hf.structure.levels import discrete_levels

    o, m = _setup(tag)
    _, load = _sources()[tag]
    Z, A = o.Ztarget, o.Atarget
    lv = discrete_levels(Z, A, o, m)
    d = deformation(Z, A, o, lv, m)
    if A % 2 == 1:  # nuclides.f90:227
        zc, nc = weak_coupling_core(o)
        cz, ca = o.Zinit - zc, o.Zinit - zc + o.Ninit - nc
        clv = discrete_levels(cz, ca, o, m)
        d = weak_coupling(d, lv, deformation(cz, ca, o, clv, m), clv, o)
    res = {"rows": 0, "mismatch": []}
    seen = set()
    for name, text in sorted(load(r"directE\d{4}\.\d{3}\.out").items()):
        for ln in _rows(text):
            parts = ln.split()
            if len(parts) < 8:
                continue
            lev, dtype, dpar = int(parts[0]), parts[6], parts[7]
            if lev in seen:
                continue
            seen.add(lev)
            res["rows"] += 1
            got = f"{float(np.float32(d.deform[lev])):.6E}"
            if dtype != d.deftype or got != dpar:
                res["mismatch"].append((name, lev, dtype, dpar, d.deftype, got))
    return res


def gate_resonances(tag: str) -> dict:
    from physics.hf.structure.resonances import resonance_parameters

    o, _ = _setup(tag)
    _, load = _sources()[tag]
    res = {"values": 0, "mismatch": []}
    checks = {
        "experimental D0 [eV]": "d0_ev",
        "experimental D0 unc. [eV]": "dd0_ev",
        "global D0 [eV]": "d0global_ev",
        "experimental D1 [eV]": "d1_ev",
        "experimental D1 unc. [eV]": "dd1_ev",
    }
    for name, text in sorted(load(r"ld\d{6}\.gs").items()):
        Z, A = int(name[2:5]), int(name[5:8])
        r = resonance_parameters(Z, A, o)
        meta = _meta(text)
        for key, attr in checks.items():
            if key in meta:
                res["values"] += 1
                got = f"{float(np.float32(getattr(r, attr))):13.6E}".strip()
                if got != meta[key]:
                    res["mismatch"].append((name, key, meta[key], got))
    for name, text in sorted(load(r"psf\d{6}\.E1").items()):
        Z, A = int(name[3:6]), int(name[6:9])
        r = resonance_parameters(Z, A, o)
        meta = _meta(text)
        for key, val in (
            ("experimental Gamma_gamma [eV]", r.gamgam_talys),
            ("experimental Gamma_gamma unc. [eV]", r.dgamgam_talys),
        ):
            if key in meta:
                res["values"] += 1
                got = f"{float(np.float32(val)):13.6E}".strip()
                if got != meta[key]:
                    res["mismatch"].append((name, key, meta[key], got))
    return res


def gate_talys_out(tag: str) -> dict:
    from physics.hf.input.nuclides import q_values

    o, m = _setup(tag)
    _, load = _sources()[tag]
    texts = load(r"talys(_head)?\.out")
    text = texts.get("talys_head.out") or texts.get("talys.out") or ""
    res = {"values": 0, "mismatch": []}
    q = q_values(m, o)
    syms = "gnpdtha"
    for t in range(7):
        mm = re.search(rf"Q\(n,{syms[t]}\):\s*(-?[\d.]+)", text)
        if mm:
            res["values"] += 1
            got = f"{q[t]:8.5f}".strip()
            if got != mm.group(1):
                res["mismatch"].append(("Q", syms[t], mm.group(1), got))
    mm = re.search(r"Target\s+:\s+\S+\s+Mass in a\.m\.u\.\s+:\s+([\d.]+)", text)
    if mm:
        res["values"] += 1
        tz, tn = 0, 1
        got = f"{float(m.mass_amu[tz, tn]):.6f}"
        if got != mm.group(1):
            res["mismatch"].append(("target mass", mm.group(1), got))
    return res


def gate_nuclides(tag: str) -> dict:
    """Nuclei with structure: TALYS's level files vs (a) the port's call-sequence replay driven by
    TALYS's own populations (bookkeeping exact?) and (b) the port's energy-bound estimate."""
    from physics.hf.input.nuclides import residual_nuclei, structure_history

    o, m = _setup(tag)
    _, load = _sources()[tag]
    have = set()
    for name in load(r"levels\d{6}\.out"):
        Z, A = int(name[6:9]), int(name[9:12])
        have.add((o.Zinit - Z, o.Ninit - (A - Z)))
    pops = _populations(tag)
    replay = set()
    if pops is not None:
        replay = set(structure_history(o, pops[0], pops[1], m, pops[2]).order)
    energies = pops[0] if pops is not None else (20.0,)
    est = set(residual_nuclei(o.Ztarget, o.Atarget, energies, o, m))
    return {
        "dump": len(have),
        "replay_missing": sorted(have - replay) if pops else None,
        "replay_extra": sorted(replay - have) if pops else None,
        "estimate": len(est),
        "missing": sorted(have - est),
        "extra": sorted(est - have),
    }


