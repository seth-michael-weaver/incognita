    if not tags:
        print("no reference dumps found")
        return 1
    tot = {
        "files": 0,
        "lines": 0,
        "lm": 0,
        "gl": 0,
        "gm": 0,
        "nm": 0,
        "rel": [],
        "dr": 0,
        "dm": 0,
        "rv": 0,
        "rm": 0,
        "qv": 0,
        "qm": 0,
        "nuc_missing": 0,
        "nuc_extra": 0,
    }
    for tag in tags:
        a = gate_levels_and_masses(tag)
        d = gate_deformation(tag)
