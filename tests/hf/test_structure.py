def test_fortran_read_blank_null_implied_decimal_and_groups():
    assert F.fortran_read("  28  58  10   S   D", "(4x, 2i4, 2(3x, a1))") == [58, 10, "S", "D"]
    # blank fields read as zero, short records are blank padded
    assert F.fortran_read("   1", "(i4, f8.3, e10.3)") == [1, 0.0, 0.0]
    # no decimal point: the edit descriptor's d applies
    assert F.fortran_read(" 1454210", "(f8.6)") == [1.45421]
    # embedded blanks are ignored (BLANK='NULL')
    assert F.fortran_read(" 1 2", "(i4)") == [12]
    assert F.fortran_read("6.520E-13 ", "(e10.3)") == [6.52e-13]


@needs_db
def test_duflo_bit_exact_against_compiled_talys():
    from physics.hf.structure.masses import duflo

    for n, z, exc in DUFLO_FORTRAN:
        assert np.float32(duflo(n, z)) == np.float32(exc), (n, z)


@needs_db
def test_units_against_known_physical_values():
    from physics.hf.input.defaults import default_options
    from physics.hf.structure.masses import masses
    from physics.hf.structure.resonances import resonance_parameters

    o = default_options(28, 58)
    m = masses(o)
    Zix, Nix = m.index(28, 58)
    assert float(m.mass_amu[Zix, Nix]) == pytest.approx(57.935342, abs=1e-6)  # AME2020, amu
    # Ni-59 neutron separation energy = Q(n,gamma) of Ni-58, 8.999 MeV
    assert float(m.s_mev[0, 0, 1]) == pytest.approx(8.9993, abs=1e-3)
    r = resonance_parameters(28, 59, o)
    assert r.d0_ev == pytest.approx(13400.0)  # 13.4 keV s-wave spacing, in eV
    assert r.s0 == pytest.approx(3.2, rel=1e-6)  # S0 = 3.2e-4, stored in units of 1e-4
    au = resonance_parameters(79, 198)
    # Au-197 + n <Gamma_gamma> is ~0.124 eV: the file (and TALYS's variable) holds keV
    assert au.gamgam_ev == pytest.approx(0.128, rel=1e-5)
    assert au.gamgam_talys == pytest.approx(1.28e-4, rel=1e-5)
    # Nrr is read from columns 133-136: "  151" -> 15 (reproduced TALYS quirk)
    assert au.nrr == 15


@needs_db
def test_masses_match_the_pre_vectorisation_capture():
    """SPEED2 turned masses()'s grid loops into numpy array operations (the same float64
    operations per cell), parses each mass table once and memoises Duflo-Zuker. The fixture
    holds every output array of the cell-by-cell code for five runs: Fe-56 and Pb-208 defaults,
    U-238 + p with FRDM, O-16 + alpha with massmodel 0 and no experimental masses (Duflo-Zuker
    everywhere), Zr-90 with HFB-D1M and user massnucleus/massexcess/beta2. Bit-identical."""
    import torch

    from physics.hf.input.defaults import PARAM_SPECS, default_options, default_params
    from physics.hf.structure.masses import masses

    z = np.load(Path(__file__).parent / "fixtures" / "masses_speed2.npz")
    cases = [
        (26, 56, "n", {}, False),
        (82, 208, "n", {}, False),
        (92, 238, "p", {"massmodel": 1}, False),
        (8, 16, "a", {"massmodel": 0, "expmass": "n"}, False),
        (40, 90, "n", {"massmodel": 3}, True),
    ]
    for i, (Z, A, proj, over, edit) in enumerate(cases):
        o = default_options(Z, A, proj, over)
        p = default_params(Z, A, o)
        if edit:
            for key, val in (("massnucleus", A + 0.0123), ("massexcess", -7.5)):
                off = PARAM_SPECS[key].offsets
                p[key][off[0] + 1, off[1] + 2] = val
                p[key][off[0] + 3, off[1]] = val * 1.1
            off = PARAM_SPECS["beta2"].offsets
            p["beta2"][off[0], off[1] + 1, off[2]] = 0.31
        m = masses(o, p)
        assert m.flagduflo == bool(z[f"m{i}_flagduflo"]), i
        for name, v in vars(m).items():
            if isinstance(v, torch.Tensor):
                assert np.array_equal(v.numpy(), z[f"m{i}_{name}"]), (i, name)


